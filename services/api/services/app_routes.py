"""Public HTTPS URLs for deployed apps.

Each project gets https://<name>-<project id>.<APPS_DOMAIN>. Caddy (on the host)
serves these: the worker writes one file with a route per app and asks Caddy to
reload. The file is rebuilt from the database every time, so a missed update is
fixed by the next sync.

- RUNNING app: proxied to its container.
- SLEEPING/WAKING app: sent to the API's wake page, which starts it again.
Every app's requests are logged to its own file; the file's modification time
is when the app was last used (see services/idle_apps.py).

Without APPS_DOMAIN (local development) apps keep their http://localhost:<port>
URL and Caddy is never touched."""

import logging
import os
import re
from dataclasses import dataclass
from pathlib import Path

import httpx
from sqlalchemy import func

from database import SessionLocal
from models.deployment import Deployment, DeploymentStatus
from models.project import Project

logger = logging.getLogger(__name__)

APPS_DOMAIN = os.getenv("APPS_DOMAIN", "").strip().lower().strip(".")

# The main Caddyfile imports CADDY_ROUTES_FILE.
CADDY_CONFIG_FILE = Path(os.getenv("CADDY_CONFIG_FILE", "/etc/caddy/Caddyfile"))
CADDY_ROUTES_FILE = Path(os.getenv("CADDY_ROUTES_FILE", "/etc/caddy/apps/apps.caddy"))
CADDY_ADMIN_URL = os.getenv("CADDY_ADMIN_URL", "http://localhost:2019").rstrip("/")

# Where Caddy writes each app's access log (same path inside the worker container).
APP_LOG_DIR = Path(os.getenv("APP_LOG_DIR", "/var/log/caddy/apps"))

# Where Caddy sends visitors of sleeping apps.
API_UPSTREAM = os.getenv("API_UPSTREAM", "127.0.0.1:8000")

ROUTES_HEADER = "# Generated by the Syphership worker from the database. Do not edit.\n"

# Statuses that have an address: live, or asleep and able to wake.
ROUTED_STATUSES = (DeploymentStatus.RUNNING, DeploymentStatus.SLEEPING, DeploymentStatus.WAKING)


@dataclass(frozen=True, order=True)
class AppRoute:
    project_id: int
    project_name: str
    status: DeploymentStatus
    host_port: int | None


def app_hostname(project_id: int, project_name: str) -> str:
    """"My Cool App", 12 -> "my-cool-app-12.<APPS_DOMAIN>".

    The ID keeps it unique (names aren't) and can never be "api"."""
    slug = re.sub(r"[^a-z0-9]+", "-", project_name.lower()).strip("-")[:40].strip("-")
    return f"{slug or 'app'}-{project_id}.{APPS_DOMAIN}"


def app_log_file(project_id: int, project_name: str) -> Path:
    return APP_LOG_DIR / f"{app_hostname(project_id, project_name)}.log"


def public_url(project_id: int, project_name: str) -> str | None:
    """The app's public HTTPS URL; None without APPS_DOMAIN."""
    if not APPS_DOMAIN:
        return None
    return f"https://{app_hostname(project_id, project_name)}"


def _site_block(app: AppRoute) -> str:
    log = (
        "    log {\n"
        f"        output file {app_log_file(app.project_id, app.project_name)} {{\n"
        "            roll_size 1mb\n"
        "            roll_keep 1\n"
        "        }\n"
        "    }\n"
    )
    if app.status == DeploymentStatus.RUNNING:
        target = f"    reverse_proxy 127.0.0.1:{app.host_port}\n"
    else:
        target = (
            f"    rewrite * /apps/{app.project_id}/wake\n"
            f"    reverse_proxy {API_UPSTREAM}\n"
        )
    return f"{app_hostname(app.project_id, app.project_name)} {{\n{log}{target}}}\n"


def render_routes(apps: list[AppRoute]) -> str:
    """The Caddyfile with one site block per app."""
    return ROUTES_HEADER + "\n".join(_site_block(app) for app in sorted(apps))


def routed_apps() -> list[AppRoute]:
    """The newest routed deployment of each project.

    During a redeploy the old and new one are both RUNNING for a moment;
    the newest wins, so traffic moves before the old container is removed."""
    db = SessionLocal()
    try:
        newest = (
            db.query(func.max(Deployment.id))
            .filter(Deployment.status.in_(ROUTED_STATUSES))
            .group_by(Deployment.project_id)
        )
        rows = (
            db.query(Project.id, Project.name, Deployment.status, Deployment.host_port)
            .join(Deployment, Deployment.project_id == Project.id)
            .filter(Deployment.id.in_(newest))
            .all()
        )
        return [
            AppRoute(project_id, name, status, host_port)
            for project_id, name, status, host_port in rows
            # A RUNNING app without a port can't be proxied to.
            if status != DeploymentStatus.RUNNING or host_port is not None
        ]
    finally:
        db.close()


def _reload_caddy() -> None:
    """Ask Caddy to load the main Caddyfile again (same as "caddy reload")."""
    response = httpx.post(
        f"{CADDY_ADMIN_URL}/load",
        content=CADDY_CONFIG_FILE.read_text(),
        headers={"Content-Type": "text/caddyfile"},
        timeout=30,
    )
    if response.status_code != 200:
        raise RuntimeError(f"Caddy reload failed ({response.status_code}): {response.text[:500]}")


def _write(path: Path, content: str) -> None:
    """Replace the file in one step, so Caddy never reads half of it."""
    tmp = path.with_suffix(".tmp")
    tmp.write_text(content)
    tmp.chmod(0o644)  # Caddy runs as its own user and must read it.
    tmp.replace(path)


def sync_app_routes() -> None:
    """Make Caddy's app routes match the database; never raises.

    Only reloads Caddy when the routes changed. If the reload fails, the old
    file is put back so the next sync tries again."""
    if not APPS_DOMAIN:
        return

    try:
        apps = routed_apps()
        content = render_routes(apps)
        previous = CADDY_ROUTES_FILE.read_text() if CADDY_ROUTES_FILE.exists() else None
        if content == previous:
            return

        _write(CADDY_ROUTES_FILE, content)
        try:
            _reload_caddy()
        except Exception:
            if previous is None:
                CADDY_ROUTES_FILE.unlink(missing_ok=True)
            else:
                _write(CADDY_ROUTES_FILE, previous)
            raise

        logger.info("App routes updated (%s apps).", len(apps))
    except Exception:
        logger.exception("Could not update app routes; will retry on the next check.")
